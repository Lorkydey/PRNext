import {readFile,writeFile,mkdir,rename,lstat} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const marker='// Generated by PRNext: typed route registry. Do not edit.';
async function changed(file,contents){
  const info=await lstat(file).catch(error=>{if(error.code!=='ENOENT')throw error;});
  if(info&&(!info.isFile()||info.isSymbolicLink()))throw Error('Typed routes cannot replace a non-regular file: '+file);
  if(await readFile(file,'utf8').catch(()=>null)===contents)return;
  const temporary=file+'.'+randomUUID()+'.tmp';try{await writeFile(temporary,contents,{mode:0o600,flag:'wx'});await rename(temporary,file);}finally{const {rm}=await import('node:fs/promises');await rm(temporary,{force:true});}
}
export function routeDeclarations(project){
  const patterns=[...new Set(project.routes.filter(route=>route.kind==='page'&&!route.internal&&!route.errorStatus).map(route=>route.pattern))].sort();
  if(patterns.length>10000)throw Error('Typed routes supports at most 10,000 page patterns');
  const fields=patterns.map(pattern=>{
    const segments=pattern.split('/');if(segments.length>33)throw Error('Typed routes supports at most 32 route segments');
    const params=segments.flatMap(part=>{
      const optional=/^\[\[\.\.\.([^\]]+)\]\]$/.exec(part),rest=/^\[\.\.\.([^\]]+)\]$/.exec(part),single=/^\[([^\]]+)\]$/.exec(part);
      const match=optional||rest||single;return match?[`${JSON.stringify(match[1])}${optional?'?':''}: ${single?'string':'string[]'}`]:[];
    });
    return `    ${JSON.stringify(pattern)}: {${params.join('; ')}};`;
  });
  return marker+'\nexport {};\ndeclare global {\n  namespace PRNext {\n    interface RouteMap {\n'+fields.join('\n')+'\n    }\n  }\n}\n';
}
// Bind missing Next-style imports to the matching PRNext declarations. Existing
// aliases remain authoritative; inherited aliases retain their resolved targets.
async function bindTypes(filename,ts){
  const source=await readFile(filename,'utf8');
  const parsed=ts.getParsedCommandLineOfConfigFile(filename,{},{...ts.sys,onUnRecoverableConfigFileDiagnostic:()=>{}});
  const paths=parsed.options.paths||{},missing=['next','next/*'].filter(name=>!Object.hasOwn(paths,name));if(!missing.length)return;
  const ast=ts.parseJsonText(filename,source),object=ast.statements[0].expression;
  const options=object.properties.find(p=>p.name?.text==='compilerOptions')?.initializer;
  const ownPaths=options?.properties?.find(p=>p.name?.text==='paths')?.initializer;
  const base=parsed.options.baseUrl||path.dirname(filename),oldBase=parsed.options.baseUrl||parsed.options.pathsBasePath||path.dirname(filename);
  const relative=file=>{let value=path.relative(base,file).replaceAll(path.sep,'/');return value.startsWith('.')?value:'./'+value;};
  const compat=fileURLToPath(new URL('../compat/',import.meta.url));
  const additions=Object.fromEntries(missing.map(name=>[name,[relative(path.join(compat,name==='next'?'index.d.ts':'*.d.cts'))]]));
  let target,values;
  if(ownPaths){if(!ts.isObjectLiteralExpression(ownPaths))throw Error('tsconfig.compilerOptions.paths must be an object');target=ownPaths;values=additions;}
  else{
    const merged={...Object.fromEntries(Object.entries(paths).map(([name,values])=>[name,values.map(value=>relative(path.resolve(oldBase,value)))])),...additions};
    if(options){if(!ts.isObjectLiteralExpression(options))throw Error('tsconfig.compilerOptions must be an object');target=options;values={paths:merged};}
    else{target=object;values={compilerOptions:{paths:merged}};}
  }
  const position=target.end-1,separator=target.properties.length&&!target.properties.hasTrailingComma?',':'';
  const text=Object.entries(values).map(([name,value])=>JSON.stringify(name)+': '+JSON.stringify(value)).join(',\n  ');
  await changed(filename,source.slice(0,position)+separator+'\n  '+text+'\n'+source.slice(position));
}
/** Include one generated root without replacing JSONC comments or inherited include globs. */
async function includeTypes(root,config,helper){
  const filename=path.resolve(root,config.typescript?.tsconfigPath||'tsconfig.json');
  const source=await readFile(filename,'utf8').catch(error=>{if(error.code==='ENOENT')return;throw error;});if(source===undefined)return;
  let ts;try{ts=createRequire(path.join(root,'package.json'))('typescript');}catch{throw Error('typedRoutes requires TypeScript installed in the application');}
  const parsed=ts.getParsedCommandLineOfConfigFile(filename,{noEmit:true},{...ts.sys,onUnRecoverableConfigFileDiagnostic:diagnostic=>{throw Error(ts.flattenDiagnosticMessageText(diagnostic.messageText,'\n'));}});
  if(!parsed||parsed.errors.some(error=>error.code!==18003))throw Error('Cannot configure typed routes: invalid tsconfig');
  if(parsed.fileNames.some(name=>path.resolve(name)===helper)){await bindTypes(filename,ts);return;}
  const ast=ts.parseJsonText(filename,source),object=ast.statements[0]?.expression;
  if(!object||!ts.isObjectLiteralExpression(object))throw Error('Cannot add typed route declarations to tsconfig');
  const property=object.properties.find(p=>p.name?.text==='files');
  let edited;
  if(property){
    if(!ts.isArrayLiteralExpression(property.initializer))throw Error('tsconfig.files must be an array');
    const array=property.initializer,position=array.end-1,separator=array.elements.length&&!array.elements.hasTrailingComma?',':'';
    edited=source.slice(0,position)+separator+JSON.stringify(path.relative(path.dirname(filename),helper).replaceAll(path.sep,'/'))+source.slice(position);
  }else{
    // TS resolves inherited files relative to this config in parsed.raw.files.
    const files=[...(parsed.raw.files||[]),path.relative(path.dirname(filename),helper).replaceAll(path.sep,'/')];
    const position=object.end-1,separator=object.properties.length&&!object.properties.hasTrailingComma?',':'';
    edited=source.slice(0,position)+separator+'\n  "files": '+JSON.stringify(files)+'\n'+source.slice(position);
  }
  await changed(filename,edited);
  await bindTypes(filename,ts);
}
export async function writeTypedRoutes(root,project,config){
  const directory=path.join(root,'.prnext-types'),file=path.join(directory,'routes.d.ts');
  const info=await lstat(directory).catch(error=>{if(error.code!=='ENOENT')throw error;});
  if(info&&(!info.isDirectory()||info.isSymbolicLink())){if(config.typedRoutes)throw Error('.prnext-types must be a real directory');return;}
  if(!config.typedRoutes){const existing=await readFile(file,'utf8').catch(()=>null);if(existing?.startsWith(marker))await changed(file,routeDeclarations({routes:[]}));return;}
  await mkdir(directory,{recursive:true,mode:0o700});
  const previous=await readFile(file,'utf8').catch(error=>{if(error.code!=='ENOENT')throw error;});
  if(previous&&!previous.startsWith(marker))throw Error('Refusing to overwrite a non-generated route registry');
  await changed(file,routeDeclarations(project));
  const helper=path.join(root,'prnext-env.d.ts'),reference='/// <reference path="./.prnext-types/routes.d.ts" />';
  const contents=await readFile(helper,'utf8').catch(error=>{if(error.code==='ENOENT')return '';throw error;});
  if(!contents.includes(reference))await changed(helper,reference+'\n'+contents);
  await includeTypes(root,config,helper);
}
